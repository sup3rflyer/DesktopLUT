def test_score_hdr_calls_a_patch_clamped_when_its_raw_target_is_outside_the_edge_at_its_luminance(law_gamut):
    sig = lattice(9, top=0.8)
    res = score_hdr(sig, RAW.ideal_xyz(sig), white_xy=D65, reachable_primaries=law_gamut)
    sp = TargetSpace(TARGET, reachable_primaries=law_gamut)
    assert np.array_equal(res["gamut_clamped"], sp.level_clamped(RAW.ideal_xyz(sig)))
    assert np.array_equal(res["ideal_xyz"], sp.ideal_xyz(sig))
    # a dim saturated blue inside the full-drive triangle (2 % toward white from the full-drive vertex, 1 nit) is
    # beyond the confirmed edge at its luminance: the full-drive target calls it reachable, the level edge clamps it
    W = _xy_to_uv(np.array(D65))[0]
    uv = W + 0.98 * (_xy_to_uv(np.array(law_gamut.full_primaries["B"])) - W)
    dim_blue = RAW.xyz_to_signal(LG._uv_to_xyz(uv, np.array([1.0])))
    assert not score_hdr(dim_blue, RAW.ideal_xyz(dim_blue), white_xy=D65,
                         reachable_primaries=law_gamut.full_primaries)["gamut_clamped"][0]
    assert score_hdr(dim_blue, RAW.ideal_xyz(dim_blue), white_xy=D65,
                     reachable_primaries=law_gamut)["gamut_clamped"][0]


