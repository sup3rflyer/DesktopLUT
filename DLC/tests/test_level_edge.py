def test_vertices_are_the_full_drive_primaries_above_the_top_read_and_the_floor_level_holds_below(law_gamut,
                                                                                                    law_block):
    g = law_gamut
    step = 10.0 ** (1.0 / LG.LEVELS_PER_DECADE)          # from the first level at/above the top read: held exactly
    for k, ch in enumerate("RGB"):
        ytop = law_block["ramps"][ch]["xyz"][-1][1]
        full = np.array(g.full_primaries[ch])
        for Y in (ytop * step * 1.0001, g.y_max * 3.0):
            assert np.abs(g.primaries_xy(np.array([Y]))[0, k] - full).max() < 1e-6
        assert np.abs(g.primaries_xy(np.array([ytop * 1.01]))[0, k] - full).max() < 1e-5   # within that level step
    assert np.array_equal(g.boundary_uv(np.array([0.01, 0.05])), g.boundary_uv(np.array([0.1, 0.1])))
    lo = g.primaries_xy(np.array([0.1]))[0]
    assert np.all(np.abs(lo - np.array([g.full_primaries[c] for c in "RGB"])).max(axis=1) > 0.01)   # dim = less saturated


