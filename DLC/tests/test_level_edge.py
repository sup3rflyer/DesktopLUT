def test_stage_cli_score_equals_the_live_verify_score_for_a_level_edge_run(tmp_path, law_block):
    from dlc.stages import score as score_stage
    calib = _hdr_calib(tmp_path, "le_verify", law_block)
    calib.calib["oog_level_edge"] = {"enabled": True, "key": law_block["key"], "reason": None,
                                     "falsification": {"passed": True}}
    calib._save()
    rng = np.random.default_rng(9)
    sig = np.vstack([_mixed_drives(20), np.repeat(np.linspace(0.1, 0.75, 10)[:, None], 3, 1),
                     rng.uniform(0.05, 0.6, (40, 3))])
    meas = RAW.ideal_xyz(sig) * (1 + 0.01 * rng.standard_normal(sig.shape))
    ti3 = _write_ti3(calib.ctx.root / "measurements" / "verify.ti3", sig, np.maximum(meas, 0.0))
    live = calib.stage_verify(str(ti3)).digest
    assert live["gamut_aware"] is True
    for key in ("full_drive_target", "reclassified", "level_edge_falsification", "verdict_depends_on_level_edge"):
        assert key in live, key
    assert set(live["full_drive_target"]) == {"core", "limits", "clamped", "tube", "all"}
    args = Namespace(stage="verify", iteration=1, source_ti3=str(ti3), gamma=2.2, luminance=None,
                     target_white_xy=None, level_edge="run", mode="HDR", run=calib.ctx.root)
    res = score_stage.build(args, calib.ctx)
    assert res.metrics["practical"] == live["practical"]
    assert res.metrics["level_edge"]["key"] == law_block["key"]
    off = score_stage.build(Namespace(**{**vars(args), "level_edge": "off"}), calib.ctx)
    assert off.metrics["practical"]["clamped"] == live["full_drive_target"]["clamped"]


