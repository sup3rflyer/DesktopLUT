def test_polygon_is_star_shaped_and_within_half_a_jnd_of_the_dense_physical_edge(law_gamut):
    g = law_gamut
    geo = g.geometry_gates()
    assert geo["star_shaped"]["ok"] and geo["anchor_order"]["ok"]
    W = _xy_to_uv(np.array(D65))[0]
    phi = np.linspace(0.0, np.pi / 2, 1025)
    ui, uj = g._code_dirs(phi)
    for Y in (0.2, 1.0, 10.0, 100.0, 600.0):
        for i, j in LG._PAIRS:
            s = g._solve_scale(i, j, np.full(len(phi), Y), ui, uj)
            X = g._xyz_at(i, j, s, ui, uj)
            X = X / X[:, 1:2] * Y
            uv = _xyz_to_uv(X)
            d = uv - W
            r = np.hypot(d[:, 0], d[:, 1])
            dirs = d / r[:, None]
            r_e = LG.ray_exit_poly(W, dirs, g.boundary_uv(np.full(len(X), Y)))
            poly = LG._uv_to_xyz(W + dirs * r_e[:, None], np.full(len(X), Y))
            de = de_itp(TargetSpace.xyz_to_ictcp(X) - TargetSpace.xyz_to_ictcp(poly))
            assert de.max() <= 0.5, (Y, i, j, de.max())


def test_level_map_keeps_in_gamut_rows_bit_identical_and_is_idempotent_and_luminance_preserving(law_gamut):
    sp = TargetSpace(TARGET, reachable_primaries=law_gamut)
    g = lattice(17, top=0.85)
    raw, out = RAW.ideal_xyz(g), sp.ideal_xyz(g)
    cl = sp.level_clamped(raw)
    assert 0 < cl.sum() < len(g)
    assert np.array_equal(out[~cl], raw[~cl])               # below 0.85 signal nothing hits the container clip
    assert np.array_equal(out[cl, 1], raw[cl, 1])           # CIE Y preserved exactly
    again = sp.ideal_xyz(sp.xyz_to_signal(out))
    lit = out[:, 1] > 0.01
    assert de_itp(RAW.xyz_to_ictcp(again[lit]) - RAW.xyz_to_ictcp(out[lit])).max() < 1e-6
    assert not np.any(sp.level_clamped(out[lit]))           # every landing point is on/inside the edge


