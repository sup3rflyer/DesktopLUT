def _h(a) -> str:
    return hashlib.sha256(np.ascontiguousarray(a, dtype=np.float64).tobytes()).hexdigest()[:16]


def test_dict_path_is_bit_identical_to_the_pre_level_edge_code():
    # Hashes computed with the pre-D4 engine (main 086b344) on the same inputs: ideal targets under both OOG
    # policies, the HDR score (dE + clamp mask) and direct / projection cubes on a synthetic sub-gamut panel.
    g = lattice(17)
    sp = TargetSpace(TARGET, reachable_primaries=PA32)
    assert _h(sp.ideal_xyz(g)) == "cbf294b42e759fb8"
    chroma = TargetSpace(Target.hdr_rec2020_pq(white_xy=D65, oog_mapping="chroma-clip"), reachable_primaries=PA32)
    assert _h(chroma.ideal_xyz(g[::7])) == "c6137a17def60b7f"
    rng = np.random.default_rng(1)
    meas = sp.ideal_xyz(g) * (1 + 0.02 * rng.standard_normal(g.shape))
    r = score_hdr(g, meas, white_xy=D65, reachable_primaries=PA32)
    assert (_h(r["de_itp"]), _h(r["gamut_clamped"].astype(float))) == ("54b55a19062966c4", "2cf4f0cb73cb1ebf")
    nat = np.array(rgb_to_xyz_matrix(*PA32["R"], *PA32["G"], *PA32["B"], *D65))
    inv = np.linalg.inv(nat)

    def panel(s):
        xyz = RAW.ideal_xyz(np.asarray(s, float))
        return (np.clip((xyz / 1e4) @ inv.T, 0.0, 0.1) * np.array([1.02, 0.99, 1.0]) @ nat.T) * 1e4
    s = np.vstack([np.repeat(np.linspace(0.05, 0.75, 12)[:, None], 3, 1), rng.uniform(0, 0.75, (300, 3))])
    m = DisplayErrorModel(s, panel(s), TARGET, reachable_primaries=PA32, smoothing=1e-3)
    for mode, want in (("direct", "51f7100b585f4116"), ("projection", "7e7113cb3e1762fc")):
        cube = build_cube(m, 9, s, oog_solve=mode, max_correction=0.25, hold_above=0.75, best_iterate=True)
        assert _h(cube) == want, mode


