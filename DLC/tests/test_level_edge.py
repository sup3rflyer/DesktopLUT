def test_run_level_edge_keeps_legacy_records_off_and_honours_a_pinned_memo(law_block):
    mp = {"level_edge": law_block}
    kw = dict(switch="auto", oog_mapping="vertex", oog_solve="projection", falsify=_passing)
    for stage in ("build-install-3dlut", "measure:verify", "verify"):
        g, rec = M.run_level_edge({"stages": {stage: {"status": "done"}}}, mp, **kw)
        assert g is None and "legacy" in rec["reason"]
    # an ABORTED build attempt (e.g. at a seam, before the memo was pinned) is not a built cube
    g, rec = M.run_level_edge({"stages": {"build-install-3dlut": {"status": "aborted"}}}, mp, **kw)
    assert g is not None and rec["enabled"] is True
    # an edge anchored on another white is refused fresh and reported as a mismatch when pinned
    g, rec = M.run_level_edge({}, mp, **kw, white_xy=(0.3000, 0.3300))
    assert g is None and "anchored on white" in rec["reason"]
    memo = {"enabled": True, "key": law_block["key"], "reason": None, "falsification": None}
    g, rec = M.run_level_edge({"oog_level_edge": memo, "stages": {"verify": {}}}, mp)
    assert g is not None and g.key() == law_block["key"]
    g, rec = M.run_level_edge({"oog_level_edge": {**memo, "key": "sha256:old"}}, mp)
    assert g is None and rec["key_mismatch"] is True and rec["current_key"] == law_block["key"]
    g, rec = M.run_level_edge({"oog_level_edge": memo}, mp, white_xy=(0.3000, 0.3300))
    assert g is None and rec["white_mismatch"] is True
    g, rec = M.run_level_edge({"oog_level_edge": {**memo, "enabled": False}}, mp, **kw)
    assert g is None and rec["enabled"] is False
    # stage CLIs: run memo by default, explicit off / on
    calib = {"oog_level_edge": memo}
    assert M.stage_level_gamut(calib, mp)[0] is not None
    assert M.stage_level_gamut({}, mp)[0] is None                    # no memo: legacy / never enabled
    assert M.stage_level_gamut(calib, mp, mode="off")[0] is None
    assert M.stage_level_gamut({}, mp, mode="on")[0] is not None
    assert M.stage_level_gamut({}, mp, mode="on", oog_mapping="chroma-clip")[0] is None
    g, note = M.stage_level_gamut(calib, mp, white_xy=(0.3000, 0.3300))    # an explicit other scoring white
    assert g is None and "anchored on white" in note
    with pytest.raises(ValueError):
        M.stage_level_gamut(calib, mp, mode="maybe")


