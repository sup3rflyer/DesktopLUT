def _write_ti3(path: Path, rgb, xyz):
    rows = [" ".join([f"{c * 100:.6f}" for c in r] + [f"{v:.6f}" for v in x]) for r, x in zip(rgb, xyz)]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("CTI3\n\nBEGIN_DATA_FORMAT\nRGB_R RGB_G RGB_B XYZ_X XYZ_Y XYZ_Z\nEND_DATA_FORMAT\n"
                    f"NUMBER_OF_SETS {len(rows)}\nBEGIN_DATA\n" + "\n".join(rows) + "\nEND_DATA\n",
                    encoding="utf-8")
    return path


def _mhc_params(block):
    p = block["full_primaries"]
    return {"primaries": {"rx": p["R"][0], "ry": p["R"][1], "gx": p["G"][0], "gy": p["G"][1],
                          "bx": p["B"][0], "by": p["B"][1]},
            "white": {"x": D65[0], "y": D65[1]}, "white_source": "d65", "target_luminance": 1000.0,
            "channel_peak_xyz": [list(v) for v in ramps()[2]], "dark_floor": {"nits": 0.1},
            "peak_chroma": {"wrgb_nonadditive": False}, "level_edge": block}


