D65 = (0.3127, 0.3290)
TARGET = Target.hdr_rec2020_pq(white_xy=D65)
RAW = TargetSpace(TARGET)
# The synthetic panel: constant OWN chromaticity per channel, own luminance ∝ PQ(code), plus the pedestal law.
OWN = {"R": (0.70, 0.30), "G": (0.18, 0.76), "B": (0.150, 0.060)}
GAIN = (0.28, 0.62, 0.08)
LAW = {"c": 0.05, "gamma": 0.5, "K": (0.26, 0.30)}
CODES = np.linspace(0.16, 0.82, 24)


def _xyY(x, y, Y=1.0):
    return np.array([x * Y / y, Y, (1.0 - x - y) * Y / y])


def law_xyz(levels, *, c=LAW["c"], gamma=LAW["gamma"], K=LAW["K"]):
    """XYZ of native drives (N, 3) on the synthetic panel: own light of each channel + ONE pedestal from the
    largest code (the two-channel composition law)."""
    levels = np.atleast_2d(np.asarray(levels, float))
    out = np.zeros((len(levels), 3))
    for k, ch in enumerate("RGB"):
        out += (GAIN[k] * LG._pq(levels[:, k]))[:, None] * _xyY(*OWN[ch])[None, :] * (levels[:, k:k + 1] > 0)
    mx = levels.max(axis=1)
    out += (c * LG._pq(mx) ** gamma * (mx > 0))[:, None] * _xyY(*K)[None, :]
    return out


def ramps(codes=CODES, **law):
    rgb = np.vstack([np.outer(codes, e) for e in np.eye(3)])
    xyz = law_xyz(rgb, **law)
    n = len(codes)
    return rgb, xyz, [xyz[(k + 1) * n - 1] for k in range(3)]


def fit(codes=CODES, wrgb=False, **law):
    rgb, xyz, peaks = ramps(codes, **law)
    return LG.fit_level_edge(rgb, xyz, channel_peak_xyz=peaks, white_xy=D65, floor_nits=0.1,
                             wrgb_nonadditive=wrgb)


def lattice(n=17, top=1.0):
    ax = np.linspace(0.0, top, n)
    B, G, R = np.meshgrid(ax, ax, ax, indexing="ij")
    return np.stack([R.ravel(), G.ravel(), B.ravel()], axis=1)


