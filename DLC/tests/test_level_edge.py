def _mixed_drives(n=60, seed=4):
    rng = np.random.default_rng(seed)
    two = []
    for i, j in LG._PAIRS:
        d = np.zeros((n, 3))
        d[:, i] = rng.uniform(0.2, 0.8, n)
        d[:, j] = d[:, i] * rng.uniform(0.0, 1.0, n)
        two.append(d)
    return np.vstack([np.vstack([np.outer(CODES, e) for e in np.eye(3)])] + two)


def test_falsification_passes_on_the_panel_that_made_the_edge_and_trips_on_another(law_gamut):
    drives = _mixed_drives()
    own = CQ.level_edge_falsification(law_gamut, drives, law_xyz(drives), floor_nits=0.1)
    assert own["passed"] is True and own["n"] > 100 and own["max_de"] < 0.5
    other = CQ.level_edge_falsification(law_gamut, drives, law_xyz(drives, c=0.0), floor_nits=0.1)
    assert other["passed"] is False and other["over_jnd"] > 0 and other["worst"]["de_itp"] > 1.0
    none = CQ.level_edge_falsification(law_gamut, drives[:3], np.zeros((3, 3)), floor_nits=0.1)
    assert none["passed"] is None and none["n"] == 0


def _colorimetric_model(gamut, n=300, seed=0):
    """A panel that decodes Rec.2020 colorimetrically and clips at its native full-drive gamut, as a trained model
    whose target space carries the level edge."""
    prim = gamut.full_primaries
    nat = np.array(rgb_to_xyz_matrix(*prim["R"], *prim["G"], *prim["B"], *D65))
    inv = np.linalg.inv(nat)

    def panel(s):
        xyz = RAW.ideal_xyz(np.asarray(s, float))
        return (np.clip((xyz / 1e4) @ inv.T, 0.0, 0.1) @ nat.T) * 1e4
    rng = np.random.default_rng(seed)
    s = np.vstack([np.repeat(np.linspace(0.05, 0.75, 12)[:, None], 3, 1), rng.uniform(0.0, 0.75, (n, 3))])
    return DisplayErrorModel(s, panel(s), TARGET, reachable_primaries=gamut, smoothing=1e-3), s, panel


def test_cube_quality_splits_by_the_level_clamp_mask_and_reports_the_dim_ramps(law_gamut):
    m, s, panel = _colorimetric_model(law_gamut)
    sp = m.space
    assert sp.level_gamut is law_gamut
    pts = CQ.sample_points(0.6, 900)
    _, inv = CQ._native_matrices(law_gamut, D65)             # a gamut -> its full-drive triangle
    lvl_mask, _ = CQ._oog_mask(sp, RAW, inv, pts)
    full_mask, _ = CQ._is_oog(RAW, inv, pts)
    assert np.array_equal(lvl_mask, sp.level_clamped(RAW.ideal_xyz(pts)))
    assert np.any(lvl_mask != full_mask)
    ideal = CQ.ideal_cube(sp, 9, 0.6)
    q = CQ.cube_quality(m, ideal, sp, law_gamut, D65, hold_above=0.6, top=0.6)
    assert q["noise_gain"]["flag"] is False and abs(q["noise_gain"]["oog"]["p99"]) < 1e-9
    dim = q["ramp_excess"]["dim"]
    assert set(dim) == {"max", "ramp"} and abs(dim["max"]) < 1e-9
    prem = CQ.premise_check(s, panel(s), TARGET, law_gamut, D65, 1000.0)
    assert prem["passed"] is True


def test_projection_remaps_guard_nodes_onto_the_edge_after_the_top_projection(law_gamut, monkeypatch):
    m, s, _ = _colorimetric_model(law_gamut)
    top = 0.6
    captured = {}
    real = lut_rbf._solve_at

    def spy(model, solve, signal_points, **kw):
        captured["solve"] = solve.copy()
        return real(model, solve, signal_points, **kw)
    monkeypatch.setattr(lut_rbf, "_solve_at", spy)
    build_cube(m, 9, s, oog_solve="projection", max_correction=0.25, hold_above=top, best_iterate=True)
    solve = captured["solve"]
    sp = m.space
    assert not np.any(sp.level_clamped(RAW.ideal_xyz(solve)))       # no guard node aims outside the edge
    # ...which the top projection alone would not guarantee (the edge narrows as the projection dims a colour):
    g = lattice(9)
    level = lut_rbf.hold_lattice_level(top, 9)
    held = g[g.max(axis=1) > level + 1e-9]
    p = np.clip(sp.xyz_to_signal(sp.ideal_xyz(held)), 0.0, 1.0)
    over = p.max(axis=1) > level + 1e-9
    assert np.any(sp.level_clamped(RAW.ideal_xyz(project_to_top(p[over], level))))


