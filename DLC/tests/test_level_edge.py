def test_fit_recovers_a_known_pedestal_law(law_block):
    b = law_block
    assert b["status"] == "ok" and b["reason"] is None
    ped = b["pedestal"]
    assert ped["identifiable"] is True
    assert abs(ped["c"] - LAW["c"]) < 1e-4 and abs(ped["gamma"] - LAW["gamma"]) < 1e-3
    assert np.allclose(ped["K_xy"], LAW["K"], atol=1e-4)
    assert all(v.get("ok") for v in b["gates"].values())
    _, _, peaks = ramps()
    want = LG._xy(np.array(peaks))
    assert b["full_primaries"] == {ch: [round(float(p[0]), 6), round(float(p[1]), 6)] for ch, p in zip("RGB", want)}
    assert b["key"].startswith("sha256:") and b["summary"]["levels"] > 200


def test_an_additive_panel_fits_as_c_zero_and_equals_the_full_drive_vertex_map(additive_block):
    # No pedestal to see (OLED / local dimming off): additive composition, c = 0 — and then the level map IS today's
    # vertex map (straight edges, white-balanced anchors), bar the membership-tolerance band and the 1e-6 rounding
    # of the persisted reads (1e-4 dE here).
    b = additive_block
    assert b["status"] == "ok" and b["pedestal"]["identifiable"] is False and b["pedestal"]["c"] == 0.0
    g = LG.LevelGamut.from_params(b)
    lvl, vtx = TargetSpace(TARGET, reachable_primaries=g), TargetSpace(TARGET, reachable_primaries=g.full_primaries)
    grid = lattice(17)
    raw, a, v = RAW.ideal_xyz(grid), lvl.ideal_xyz(grid), vtx.ideal_xyz(grid)
    cl_l = lvl.level_clamped(raw)
    cl_v = np.any(np.abs(v - raw) > 1e-9 + 1e-6 * np.abs(raw).sum(1)[:, None], axis=1)
    import colour
    over = colour.XYZ_to_RGB(raw / 1e4, vtx._reachable).max(axis=1) > 1 + 1e-4       # container clip (≈10000 nit)
    same = (cl_l == cl_v) & ~over
    d = de_itp(RAW.xyz_to_ictcp(a) - RAW.xyz_to_ictcp(v))
    assert same.sum() > 0.99 * (~over).sum() and d[same].max() < 1e-3
    r, r_e, _ = LG.outside_distance(g, raw[(cl_l != cl_v) & ~over])
    assert np.all(np.abs(r / r_e - 1.0) < 1e-4)                                          # only the tolerance band


def test_gates_turn_the_edge_off_with_a_reason():
    few = fit(codes=np.linspace(0.3, 0.8, 7))
    assert few["status"] == "rejected" and "too few" in few["reason"]
    wrgb = fit(wrgb=True)
    assert wrgb["status"] == "rejected" and "WRGB" in wrgb["reason"]
    unknown = fit(wrgb=None)                                 # the MHC build's WRGB verdict unavailable: not "additive"
    assert unknown["status"] == "rejected" and "unavailable" in unknown["reason"]
    steep = fit(gamma=1.5)                                   # a pedestal growing faster than the light: no law fit
    assert steep["status"] == "rejected" and "bound" in steep["reason"]
    kout = fit(K=(0.6, 0.6))                                 # pedestal chromaticity outside the native triangle
    assert kout["status"] == "rejected" and "not strictly inside" in kout["reason"]
    rgb, xyz, peaks = ramps()                                # two dim blue dropouts far below the pedestal
    xyz = xyz.copy()
    xyz[2 * len(CODES):2 * len(CODES) + 2] *= 0.02
    drop = LG.fit_level_edge(rgb, xyz, channel_peak_xyz=peaks, white_xy=D65, floor_nits=0.001)
    assert drop["status"] == "rejected" and "pedestal exceeds" in drop["reason"]
    for b in (few, wrgb, unknown, steep, kout, drop):
        gamut, rec = M.run_level_edge({}, {"level_edge": b}, switch="auto", oog_solve="projection")
        assert gamut is None and rec["enabled"] is False and "rejected" in rec["reason"]
        with pytest.raises(ValueError):
            LG.LevelGamut.from_params(b)
    missing = LG.fit_level_edge(np.zeros((3, 3)), np.zeros((3, 3)), channel_peak_xyz=None, white_xy=D65,
                                floor_nits=None)
    assert missing["status"] == "unavailable" and missing["reason"]


def test_multistart_keeps_the_interior_minimum_over_a_bound_local_minimum(monkeypatch):
    # A bad start stalls on a bound (γ = 1, rms ~0.015 on the PA32UCXR); the deterministic multi-start keeps the
    # lowest cost, so the edge is not rejected for a start that happened to fail.
    import scipy.optimize as so
    real = so.least_squares
    seen = []

    def fake(fun, x0, args=(), bounds=None, **kw):
        seen.append(x0[3])
        r = real(fun, x0, args=args, bounds=bounds, **kw)
        if x0[3] == 0.25:                                    # this start "stalls" on the gamma bound
            r.x = np.array([x0[0], x0[1], 0.2, 1.0])
            r.fun = fun(r.x, *args)
            r.cost = 0.5 * float(np.sum(r.fun ** 2))
            r.active_mask = np.array([0, 0, 0, 1])
        return r
    monkeypatch.setattr(so, "least_squares", fake)
    b = fit()
    assert sorted(seen) == [0.25, 0.5, 0.75]
    assert b["status"] == "ok" and abs(b["pedestal"]["gamma"] - LAW["gamma"]) < 1e-3


def test_key_is_stable_and_a_tampered_block_is_refused(law_block):
    again = fit()
    assert again["key"] == law_block["key"]
    rt = json.loads(json.dumps(law_block))                  # the run-record round trip
    assert LG.LevelGamut.from_params(rt).key() == law_block["key"]
    bad = json.loads(json.dumps(law_block))
    bad["ramps"]["B"]["xyz"][3][1] *= 1.01
    with pytest.raises(ValueError, match="key"):
        LG.LevelGamut.from_params(bad)
    # a pinned run whose record was edited: no crash — treated as a key mismatch (the orchestrator's seam) / unusable
    memo = {"enabled": True, "key": law_block["key"], "reason": None, "falsification": None}
    g, rec = M.run_level_edge({"oog_level_edge": memo}, {"level_edge": bad})
    assert g is None and rec["key_mismatch"] is True
    g, note = M.stage_level_gamut({"oog_level_edge": memo}, {"level_edge": bad})
    assert g is None and "unusable" in note


