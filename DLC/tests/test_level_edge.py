"""Level edge (design D4) — the luminance-dependent confirmed gamut edge (engine/level_gamut.py) and its wiring.

On a FALD / LC panel a dim primary is less saturated than the full-drive one (the LED pedestal leaks through the
closed cells): XYZ(pure k at code m) = own_k(m) + c·PQ(m)^γ·K. The edge is fitted from the raw pure-channel ramps,
persisted in mhc_params["level_edge"], and — only with the profile switch on, the vertex policy, the projection
solve, its deterministic gates passed and no falsification — replaces the full-drive triangle for the build and
verify targets. These pin the contract on synthetic panels generated BY the law (the suite never reads runs/):
the dict path stays bit-identical to the pre-D4 code, the fit recovers a known law, the map lands a Rec.2020
primary on the measured vertex at its luminance, the gates turn the feature off with a reason, the memo rules keep
legacy runs legacy, and a stage-CLI score equals the live verify.
"""
