"""Render a self-contained HTML run report — a permanent artifact the Export button writes.

It embeds the run state + chart data and inlines the shared chart renderer (``charts.js``),
so the file opens later with no server and reproduces the dashboard's charts. The summary
numbers are server-rendered as static HTML, so they're legible even with scripting off.
Stdlib-only (html + json), like the rest of the dashboard.
"""

from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any, Optional


def _num(v: Any, d: int = 2) -> str:
    try:
        return f"{float(v):.{d}f}"
    except (TypeError, ValueError):
        return "—"


def _row(label: str, value: Any) -> str:
    return f"<tr><th>{html.escape(label)}</th><td>{html.escape('' if value is None else str(value))}</td></tr>"


def _de_table(de: dict[str, Any]) -> str:
    if not de:
        return "<p class='muted'>No scored ΔE yet (verify has not run).</p>"
    cells = [("avg", de.get("avg")), ("95th", de.get("p95")), ("99th", de.get("p99")),
             ("max", de.get("max")), ("white", de.get("white")),
             ("grayscale", de.get("grayscale")), ("colour", de.get("colour"))]
    tds = "".join(f"<div class='bn'><b>{_num(v)}</b><label>{html.escape(k)}</label></div>" for k, v in cells)
    src = de.get("phase") or ""
    return f"<div class='bignums'>{tds}</div><p class='muted'>source: {html.escape(str(src))}</p>"


def _safe_json(obj: Any) -> str:
    # Embed in a <script> without letting a literal </script> or HTML comment break out.
    return (json.dumps(obj, separators=(",", ":"))
            .replace("</", "<\\/").replace("<!--", "<\\!--"))


def render_report_html(snap: dict[str, Any], charts: dict[str, Any], exported_at: str,
                       assets_dir: Path) -> str:
    """Build the standalone report HTML for one point-in-time snapshot."""
    h = snap.get("header") or {}
    white = h.get("white") or {}
    counters = snap.get("counters") or {}
    timers = snap.get("timers") or {}
    run_id = h.get("run_id") or snap.get("run_id") or "run"

    summary = "".join([
        _row("run", run_id),
        _row("display", h.get("display")),
        _row("monitor", h.get("monitor")),
        _row("mode", h.get("mode")),
        _row("flow", h.get("flow")),
        _row("bit depth", h.get("bit_depth")),
        _row("target", h.get("target")),
        _row("gamma", h.get("gamma")),
        _row("white", (f"{_num(white.get('cct'),0)} K  ({_num((white.get('xy') or [None,None])[0],4)}, "
                       f"{_num((white.get('xy') or [None,None])[1],4)})" if white else None)),
        _row("ccmx", h.get("ccmx")),
        _row("spd", h.get("spd")),
        _row("status", snap.get("run_status")),
        _row("patches", f"{counters.get('patches_done', 0)} / {counters.get('patches_total', 0)}"),
        _row("reads (ok/fail)", f"{counters.get('reads_ok', 0)} / {counters.get('reads_failed', 0)}"),
        _row("run elapsed", _num(timers.get("run_elapsed_s"), 0) + " s" if timers.get("run_elapsed_s") is not None else None),
        _row("exported", exported_at),
    ])

    try:
        charts_js = (assets_dir / "charts.js").read_text(encoding="utf-8")
    except OSError:
        charts_js = ""

    chart_cards = "".join(
        f'<figure class="chart"><figcaption>{html.escape(title)}</figcaption>'
        f'<div data-chart="{key}"></div></figure>'
        for key, title in (("cie", "Color Accuracy · CIE 1931"), ("eotf", "Tone Response · EOTF"),
                           ("graycct", "Grayscale CCT"), ("grayduv", "Grayscale Duv"),
                           ("colorlum", "Color Luminance"), ("saturation", "Saturation tracking"),
                           ("optimizer", "Optimizer convergence"), ("drift", "White CCT vs time")))

    payload = _safe_json({"charts": charts, "header": h})

    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"/>
<title>DLC report · {html.escape(str(run_id))}</title>
<style>{_REPORT_CSS}</style></head>
<body>
<h1>DLC calibration report</h1>
<div class="cols">
  <section class="card"><h2>Summary</h2><table class="kv">{summary}</table></section>
  <section class="card"><h2>ΔE2000</h2>{_de_table(snap.get('de') or {})}</section>
</div>
<section class="card"><h2>Charts</h2><div class="charts" id="charts">{chart_cards}</div></section>
<p class="muted">Generated by the DLC mission-control dashboard — self-contained (no server needed).</p>
<script id="report-data" type="application/json">{payload}</script>
<script>{charts_js}</script>
<script>
(function(){{
  try {{
    var D = JSON.parse(document.getElementById("report-data").textContent);
    if (window.DLCCharts) window.DLCCharts.renderInto(document.getElementById("charts"), D.charts, D.header);
  }} catch (e) {{ console.error("report render failed", e); }}
}})();
</script>
</body></html>"""


